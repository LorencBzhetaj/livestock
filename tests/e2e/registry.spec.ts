import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

const testPhoto = 'public/icon-192.png'

async function englishOffline(page: Page) {
  await page.goto('/settings')
  await page.getByLabel('Gjuha', { exact: true }).selectOption('en')
  await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await page.context().setOffline(true)
  await page.getByRole('link', { name: 'Animals', exact: true }).click()
}

test('registers, edits, searches, filters and archives an animal offline', async ({ page, context }) => {
  await page.goto('/animals')
  await expect(page.getByRole('heading', { name: 'Kafshët' })).toBeVisible()
  await expect(page.getByText('Nuk ka ende kafshë të regjistruara.')).toBeVisible()
  await englishOffline(page)

  await page.getByRole('link', { name: 'Add animal' }).click()
  await expect(page.getByRole('combobox', { name: 'Species', exact: true }).locator('option:checked')).toHaveText('Goat')
  await page.getByLabel('Ear tag').fill(' al-42 ')
  await page.getByLabel('Name', { exact: true }).fill('Bora')
  await page.getByLabel('Breed').fill('Alpine')
  await page.getByRole('combobox', { name: 'Sex', exact: true }).selectOption('female')
  await page.getByLabel('Birth date', { exact: true }).fill('2020-01-12')
  await page.getByLabel('Acquisition date').fill('2021-03-01')
  await page.getByLabel('Origin').fill('Farm A')
  await page.getByLabel('Notes').fill('Single line of notes')
  await page.getByLabel('Photograph', { exact: true }).setInputFiles(testPhoto)
  await page.getByRole('button', { name: 'Save animal' }).click()
  await expect(page.getByRole('heading', { name: 'Bora' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Photograph' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Veterinary history' })).toBeVisible()
  const profile = page.url()

  await page.getByRole('link', { name: 'Edit animal' }).click()
  await page.getByLabel('Name', { exact: true }).fill('Lule')
  await page.getByRole('button', { name: 'Save animal' }).click()
  await expect(page.getByRole('heading', { name: 'Lule' })).toBeVisible()
  expect(page.url()).toBe(profile)

  await page.getByRole('link', { name: 'Back to registry' }).click()
  await page.getByRole('link', { name: 'Add animal' }).click()
  await expect(page.getByRole('heading', { name: 'Add animal' })).toBeVisible()
  await page.getByLabel('Ear tag').fill('al-42')
  await page.getByRole('combobox', { name: 'Sex', exact: true }).selectOption('male')
  await page.getByRole('button', { name: 'Save animal' }).click()
  await expect(page.getByRole('alert')).toContainText('An active animal already has this ear tag.')
  await page.getByRole('link', { name: 'Cancel' }).click()

  await page.getByLabel('Search by ear tag or name').fill('lule')
  await page.getByRole('combobox', { name: 'Species', exact: true }).selectOption({ label: 'Goat' })
  await page.getByRole('combobox', { name: 'Breed', exact: true }).selectOption({ label: 'Alpine' })
  await page.getByRole('combobox', { name: 'Sex', exact: true }).selectOption('female')
  await page.getByRole('combobox', { name: 'Age', exact: true }).selectOption('fourPlus')
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('active')
  await expect(page.getByRole('link', { name: /AL-42 Lule/ })).toBeVisible()
  await page.getByRole('combobox', { name: 'Sex', exact: true }).selectOption('male')
  await expect(page.getByText('No animals match these filters.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByRole('link', { name: /AL-42 Lule/ }).click()

  await page.getByRole('button', { name: 'Archive animal', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm archive' }).click()
  await expect(page.getByText('Archived', { exact: true })).toBeVisible()
  await page.close()
  const reopened = await context.newPage()
  await reopened.goto(profile)
  await expect(reopened.getByRole('heading', { name: 'Lule' })).toBeVisible()
  await expect(reopened.getByText('Archived', { exact: true })).toBeVisible()
  await expect.poll(() => reopened.getByRole('img', { name: 'Photograph' }).evaluate((image: HTMLImageElement) => image.naturalWidth)).toBe(192)
  await expect(reopened.locator('.sync-inline')).toContainText('Offline')
  expect(await reopened.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(reopened.viewportSize()!.width)
  await reopened.getByRole('link', { name: 'Back to registry' }).click()
  await reopened.getByRole('combobox', { name: 'Status', exact: true }).selectOption('active')
  await expect(reopened.getByText('No animals match these filters.')).toBeVisible()
  await reopened.getByRole('combobox', { name: 'Status', exact: true }).selectOption('archived')
  await expect(reopened.getByRole('link', { name: /AL-42 Lule/ })).toBeVisible()
})

test('downloads a CSV template, previews errors and imports 200 records only after confirmation offline', async ({ page }) => {
  await englishOffline(page)
  await page.getByRole('link', { name: 'Import CSV' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download CSV template' }).click()
  const template = await downloadPromise
  expect(await readFile(await template.path(), 'utf8')).toMatch(/^earTag,species,sex,/)

  const csv = page.getByLabel('CSV file')
  const upload = (contents: string) => csv.setInputFiles({
    name: 'animals.csv', mimeType: 'text/csv', buffer: Buffer.from(contents),
  })
  await upload('earTag,species,sex\nAL-1,goat,female\n al-1 ,goat,male\n,SHEEP,')
  await expect(page.getByText('This ear tag is repeated in the file.')).toHaveCount(2)
  await expect(page.getByText('Ear tag · Missing or invalid value')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirm import' })).toBeDisabled()
  await page.getByRole('link', { name: 'Back to registry' }).click()
  await expect(page.getByText('No animals have been registered yet.')).toBeVisible()
  await page.getByRole('link', { name: 'Import CSV' }).click()
  const batch = Array.from({ length: 200 }, (_, index) => 'AL-' + (index + 1) + ',goat,female')
  await upload('earTag,species,sex\n' + batch.join('\n'))
  await expect(page.getByRole('heading', { name: 'Import preview' })).toBeVisible()
  await expect(page.getByText('Ready to import · 200 / 200')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.getByRole('button', { name: 'Confirm import' }).click()
  await expect(page.getByText('Animals imported · 200')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Animals shown · 200 / 200')).toBeVisible()
  await page.getByLabel('Search by ear tag or name').fill('al-200')
  await expect(page.getByRole('link', { name: /AL-200/ })).toBeVisible()
  await expect(page.getByText('Animals shown · 1 / 200')).toBeVisible()
  await page.getByRole('link', { name: 'Import CSV' }).click()
  await upload('earTag,species,sex\n al-200 ,sheep,male\nAL-201,goat,female')
  await expect(page.getByText('This ear tag already exists in the registry.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirm import' })).toBeDisabled()
})
