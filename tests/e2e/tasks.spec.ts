import { expect, test, type Page } from '@playwright/test'

test.use({ timezoneId: 'America/Los_Angeles' })
const instant = new Date('2026-03-09T06:30:00Z')
const today = '2026-03-08'

async function offline(page: Page) {
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await page.context().setOffline(true)
}

test('creates, edits, reschedules, filters, completes and cancels tasks offline across local midnight', async ({ page }) => {
  await page.clock.setFixedTime(instant)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Regjistri i fermës' })).toBeVisible()
  await offline(page)
  await page.getByRole('link', { name: 'Shto detyrë' }).click()
  await expect(page.getByLabel('Data e afatit')).toHaveValue(today)
  await page.getByLabel('Titulli').fill('Test local task')
  await page.getByLabel('Përshkrimi').fill('Test description')
  await page.getByLabel('Data e afatit').fill('2026-03-07')
  await page.getByRole('button', { name: 'Ruaj detyrën' }).click()
  await expect(page.getByRole('heading', { name: 'Test local task' })).toBeVisible()
  await expect(page.getByText('Me vonesë', { exact: true })).toBeVisible()
  const details = page.url()

  await page.getByRole('link', { name: 'Cilësimet', exact: true }).click()
  await page.getByLabel('Gjuha', { exact: true }).selectOption('en')
  await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible()
  await page.goto(details)
  await page.getByRole('link', { name: /Reschedule/ }).click()
  await page.getByLabel('Title', { exact: true }).fill('Revised task')
  await page.getByLabel('Due date').fill(today)
  await page.getByRole('combobox', { name: 'Task type', exact: true }).selectOption('checkup')
  await page.getByRole('button', { name: 'Save task' }).click()
  await expect(page.getByRole('heading', { name: 'Revised task' })).toBeVisible()
  await expect(page.locator('time[datetime="2026-03-08"]')).toBeVisible()
  await expect(page.getByText('Overdue', { exact: true })).toHaveCount(0)

  await page.getByRole('navigation').getByRole('link', { name: 'Calendar', exact: true }).click()
  const agenda = page.getByRole('region', { name: 'Daily agenda' })
  await expect(agenda.getByLabel('Agenda date')).toHaveValue(today)
  await expect(agenda.getByRole('link', { name: 'Revised task' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Mar 8, 2026 · Task 1/ })).toBeVisible()
  await page.getByLabel('From date').fill('2026-03-09')
  await expect(agenda.getByText('No tasks in this view.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByLabel('From date')).toHaveValue('')
  await expect(agenda.getByRole('link', { name: 'Revised task' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Task type', exact: true }).selectOption('general')
  await expect(agenda.getByText('No tasks in this view.')).toBeVisible()
  await page.getByRole('combobox', { name: 'Task type', exact: true }).selectOption('checkup')
  await agenda.getByRole('link', { name: 'Revised task' }).click()
  await page.getByRole('button', { name: 'Complete task' }).click()
  await expect(page.getByText('Completed', { exact: true })).toBeVisible()

  await page.getByRole('navigation').getByRole('link', { name: 'Calendar', exact: true }).click()
  await page.getByRole('link', { name: 'Add task' }).click()
  await page.getByLabel('Title', { exact: true }).fill('Cancelled test')
  await page.getByRole('button', { name: 'Save task' }).click()
  await page.getByRole('button', { name: 'Cancel task' }).click()
  await page.getByRole('button', { name: 'Confirm cancellation' }).click()
  await expect(page.getByText('Cancelled', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Cancelled', { exact: true })).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'Calendar', exact: true }).click()
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('completed')
  await expect(agenda.getByRole('link', { name: 'Revised task' })).toBeVisible()
  await expect(agenda.getByRole('link', { name: 'Cancelled test' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('shows live counts for 200 animals and creates one confirmed reminder from the latest record offline', async ({ page }) => {
  await page.clock.setFixedTime(instant)
  await page.goto('/settings')
  await page.getByLabel('Gjuha', { exact: true }).selectOption('en')
  await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible()
  await offline(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Animals', exact: true }).click()
  await page.getByRole('link', { name: 'Import CSV' }).click()
  const rows = Array.from({ length: 200 }, (_, index) =>
    'TEST-' + (index + 1) + ',' + (index < 150 ? 'goat' : 'sheep') + ',female,' + (index < 20 ? 'archived' : 'active'))
  const csv = 'earTag,species,sex,status\n' + rows.join('\n')
  await page.getByLabel('CSV file').setInputFiles({ name: 'herd.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: 'Confirm import' }).click()
  await expect(page.getByText('Animals imported · 200')).toBeVisible()
  await page.getByRole('link', { name: /^TEST-1\b/ }).click()
  await expect(page.getByRole('heading', { name: 'TEST-1', exact: true })).toBeVisible()
  const profile = page.url()
  await expect(page.getByText('Archived', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Add veterinary event' }).click()
  await page.getByRole('combobox', { name: 'Event type', exact: true }).selectOption('vaccination')
  await page.getByLabel('Event date', { exact: true }).fill('2026-03-06')
  await page.getByLabel('Vaccine name').fill('Recorded test vaccine')
  await page.getByLabel('Next vaccination date').fill('2026-03-09')
  await page.getByRole('button', { name: 'Save event' }).click()
  await expect(page.getByRole('heading', { name: 'Vaccination', exact: true })).toBeVisible()
  const original = page.url()

  await page.getByRole('navigation').getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Registered animals' })).toContainText('200')
  await expect(page.getByRole('region', { name: 'Active animals' })).toContainText('180')
  await expect(page.getByRole('region', { name: 'Archived animals' })).toContainText('20')
  await expect(page.getByText('Goat', { exact: true })).toBeVisible()
  await expect(page.getByText('Sheep', { exact: true })).toBeVisible()
  await expect(page.getByText('Date from the veterinary record')).toBeVisible()
  await expect(page.getByRole('link', { name: 'Next 7 days 0' })).toBeVisible()

  await page.goto(original)
  await page.getByRole('link', { name: 'Add amendment' }).click()
  await page.getByLabel('Next vaccination date').fill('2026-03-11')
  await page.getByLabel('Reason for amendment').fill('Test correction')
  await page.getByRole('button', { name: 'Save event' }).click()
  await expect(page.getByRole('heading', { name: 'Vaccination · Amendment' })).toBeVisible()
  const latest = page.url()
  await page.goto(original)
  await page.getByRole('button', { name: 'Create reminder' }).click()
  await expect(page.getByText(/Review reminder · Mar 11, 2026/)).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open reminder' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Confirm reminder' }).click()
  await page.getByRole('link', { name: 'Open reminder' }).click()
  await expect(page.locator('time[datetime="2026-03-11"]')).toBeVisible()
  await expect(page.getByText(/Archived/)).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open latest version' })).toHaveAttribute('href', new URL(latest).pathname)
  await expect(page.getByRole('link', { name: 'TEST-1', exact: true })).toHaveAttribute('href', new URL(profile).pathname)
  const taskUrl = page.url()
  await page.goto(latest)
  await expect(page.getByRole('link', { name: 'Open reminder' })).toHaveAttribute('href', new URL(taskUrl).pathname)
  await expect(page.getByRole('button', { name: 'Create reminder' })).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Next 7 days 1' })).toBeVisible()
  await expect(page.getByText('Offline · This device only')).toBeVisible()
})
