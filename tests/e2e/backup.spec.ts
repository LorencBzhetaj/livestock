import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('downloads and restores an offline backup with preview, photo, language and preserved peer draft', async ({ page, context }) => {
  await page.goto('/settings')
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Shto të dhënat DEMO' }).click()
  await expect(page.getByText('Të dhënat DEMO janë shtuar në këtë pajisje.')).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'Kafshët' }).click()
  await page.getByRole('link', { name: /^DEMO-001/ }).click()
  await expect(page.getByRole('heading', { name: 'DEMO-001', exact: true })).toBeVisible()
  const profile = page.url()
  await page.getByRole('link', { name: 'Ndrysho kafshën' }).click()
  await page.getByLabel('Fotografia', { exact: true }).setInputFiles('public/icon-192.png')
  await page.getByRole('button', { name: 'Ruaj kafshën' }).click()
  await expect(page.getByRole('img', { name: 'Fotografia' })).toBeVisible()
  await page.getByRole('button', { name: /^Fshi kafshën/ }).click()
  await page.getByRole('button', { name: 'Po, fshije' }).click()
  await expect(page).toHaveURL(/\/animals$/)
  await expect(page.getByRole('link', { name: /^DEMO-001/ })).toHaveCount(0)
  await page.getByRole('button', { name: /^Shiko të fshirat/ }).click()
  await expect(page.getByRole('link', { name: /^DEMO-001/ })).toBeVisible()
  await page.goto(profile)
  await expect(page.getByText('E arkivuar', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Cilësimet' }).click()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Shkarko kopjen rezervë' }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toMatch(/\.backup\.json$/)
  const bytes = await readFile(await download.path())
  const body = JSON.parse(bytes.toString('utf8'))
  expect(body.counts).toMatchObject({ animals: 3, animalPhotos: 1 })
  await expect(page.getByText(/Shkarkimi u nis · .*KiB/)).toBeVisible()

  await page.getByLabel('Gjuha', { exact: true }).selectOption('en')
  await expect(page.getByRole('heading', { name: 'Backup & restore' })).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'Animals' }).click()
  await page.getByRole('link', { name: 'Add animal' }).click()
  await expect(page.getByRole('heading', { name: 'Add animal' })).toBeVisible()
  await page.getByLabel('Ear tag').fill('SYNTHETIC-LATER')
  await page.getByRole('combobox', { name: 'Sex' }).selectOption('female')
  await page.getByRole('button', { name: 'Save animal' }).click()
  await expect(page.getByRole('heading', { name: 'SYNTHETIC-LATER', exact: true })).toBeVisible()

  const peer = await context.newPage()
  await peer.goto('/animals')
  await expect(peer.getByRole('link', { name: /^SYNTHETIC-LATER/ })).toBeVisible()
  await peer.getByRole('link', { name: 'Add animal' }).click()
  await expect(peer.getByRole('heading', { name: 'Add animal' })).toBeVisible()
  await peer.getByLabel('Ear tag').fill('UNSAVED-PEER-DRAFT')
  await page.getByRole('navigation').getByRole('link', { name: 'Settings' }).click()
  const select = page.getByLabel('Backup file')
  const corrupted = { ...body, checksum: '0'.repeat(64) }
  await select.setInputFiles({ name: 'corrupt.backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(corrupted)) })
  await expect(page.getByRole('alert')).toContainText('Integrity verification failed')
  await expect(peer.getByLabel('Ear tag')).toHaveValue('UNSAVED-PEER-DRAFT')
  await select.setInputFiles({ name: download.suggestedFilename(), mimeType: 'application/json', buffer: bytes })
  await expect(page.getByRole('heading', { name: 'Restore preview' })).toBeVisible()
  await expect(page.getByText('Supported format. SHA-256 verification passed.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Restore backup' })).toBeDisabled()
  await expect(peer.getByLabel('Ear tag')).toHaveValue('UNSAVED-PEER-DRAFT')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)

  await page.getByRole('checkbox', { name: 'I confirm replacement of all local application data.' }).check()
  await page.getByRole('button', { name: 'Restore backup' }).click()
  await expect(page.getByText('Të dhënat u rikthyen.', { exact: true })).toBeVisible()
  await expect(peer.getByText(/Të dhënat u rikthyen në një skedë tjetër/)).toBeVisible()
  await expect(peer.getByLabel('Etiketa e veshit')).toHaveValue('UNSAVED-PEER-DRAFT')
  await peer.goto('/animals')
  await expect(peer.getByRole('heading', { name: 'Kafshët' })).toBeVisible()
  await expect(peer.getByRole('link', { name: /^DEMO-003/ })).toBeVisible()
  await expect(peer.getByRole('link', { name: /^SYNTHETIC-LATER/ })).toHaveCount(0)
  await page.goto(profile)
  await expect.poll(() => page.getByRole('img', { name: 'Fotografia' })
    .evaluate((image: HTMLImageElement) => image.naturalWidth)).toBe(192)
  await expect(page.getByText('E arkivuar', { exact: true })).toBeVisible()
  await expect(page.locator('.sync-inline')).toContainText('Pa internet')
})
