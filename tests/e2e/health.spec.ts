  const profile = page.url()
  await page.getByRole('link', { name: 'Shto ngjarje veterinare' }).click()
  await page.getByLabel('Data e ngjarjes', { exact: true }).fill(exampleDate)
  await page.getByLabel('Arsyeja ose diagnoza').fill('Kontroll prove')
  await page.getByLabel('Simptomat').fill('Simptoma të regjistruara')
  await page.getByLabel('Gjetjet').fill('Gjetje prove')
  await page.getByLabel('Diagnoza', { exact: true }).fill('Diagnozë prove')
  await page.getByLabel('Veterineri', { exact: true }).fill('Dr. Test')
  await page.getByLabel('Data e vizitës pasuese').fill('2026-10-08')
  await page.getByRole('button', { name: 'Ruaj ngjarjen' }).click()
  await expect(page.getByRole('heading', { name: 'Kontroll veterinar' })).toBeVisible()
  await expect(page.getByText('Gjetje prove')).toBeVisible()

  await page.getByRole('link', { name: 'Cilësimet' }).click()
